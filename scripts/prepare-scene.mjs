/**
 * Prepares the committed assets of the painted Home hero. Run it by hand, never during
 * `next build`, and commit what it writes. See scripts/scene/README.md for provenance.
 *
 *   npm run scene:prepare -- [--from=<dir>] [--ffmpeg=<path>] [--skip-audio]
 *
 * Writes:
 *   public/scene/{day,night}.avif                 painting JPEG, AVIF q55 effort 4, no resize
 *   public/scene/{day,night}.webp                 painting JPEG, WebP q80, no resize
 *   public/scene/dragon-{up,level,down}.webp      copied from assets/rear-body-*.webp
 *   public/scene/dragon-tail.webp                 copied from assets/rear-tailtex.webp
 *   public/scene/dragon-full-{up,level,down}.webp assets/rear-keyed-*.png as WebP q82, alpha q90
 *   src/components/sections/home/dragon/dragon-spine.ts   from assets/rear-spine.json
 *   public/audio/ride-the-wind.mp3                the whole song, re-encoded (CBR 112 kb/s, tags kept)
 *
 *   --from=<dir>       the scene inputs (source/, assets/, audio/); default D:/Projects/Porfolio-V2/.planning/painted-hero
 *   --ffmpeg=<path>    an ffmpeg with libmp3lame; default $FFMPEG, then `ffmpeg` on PATH
 *   --skip-audio       leave the MP3 alone
 *
 * Exits 1 on any failure (missing input, wrong MP3 checksum, ffmpeg error), 2 on a usage error.
 */
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { copyFile, mkdir, readFile, stat, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const SCENE_DIR = join(ROOT, 'public', 'scene');
const AUDIO_OUT = join(ROOT, 'public', 'audio', 'ride-the-wind.mp3');
const SPINE_OUT = join(ROOT, 'src', 'components', 'sections', 'home', 'dragon', 'dragon-spine.ts');
const DEFAULT_FROM = 'D:/Projects/Porfolio-V2/.planning/painted-hero';
const SONG_SHA256 = '0adeacb87531510d91ab2b88b92ea6625e27d7346de1dc0011a8d9b3bd41388e';
const POSES = ['up', 'level', 'down'];
const SPINE_ARRAYS = ['x', 'y', 'nx', 'ny', 's'];

const USAGE = 'Usage: node scripts/prepare-scene.mjs [--from=<dir>] [--ffmpeg=<path>] [--skip-audio]';

class UsageError extends Error {}

function parseArgs(argv) {
  const options = { from: DEFAULT_FROM, ffmpeg: process.env.FFMPEG || 'ffmpeg', skipAudio: false };
  for (const arg of argv) {
    if (arg.startsWith('--from=')) options.from = arg.slice('--from='.length);
    else if (arg.startsWith('--ffmpeg=')) options.ffmpeg = arg.slice('--ffmpeg='.length);
    else if (arg === '--skip-audio') options.skipAudio = true;
    else throw new UsageError(`Unknown argument: ${arg}`);
  }
  return { ...options, from: resolve(options.from) };
}

async function report(path) {
  const { size } = await stat(path);
  console.log(`${path.slice(ROOT.length).replaceAll('\\', '/')}  ${size} B`);
}

async function writePaintings(from) {
  for (const name of ['day', 'night']) {
    const input = join(from, 'source', `painting-${name}.jpg`);
    const avif = join(SCENE_DIR, `${name}.avif`);
    const webp = join(SCENE_DIR, `${name}.webp`);
    await sharp(input).avif({ quality: 55, effort: 4 }).toFile(avif);
    await sharp(input).webp({ quality: 80 }).toFile(webp);
    await report(avif);
    await report(webp);
  }
}

async function copyDragonFrames(from) {
  const copies = POSES.map((pose) => [`rear-body-${pose}.webp`, `dragon-${pose}.webp`]);
  copies.push(['rear-tailtex.webp', 'dragon-tail.webp']);
  for (const [input, output] of copies) {
    await copyFile(join(from, 'assets', input), join(SCENE_DIR, output));
    await report(join(SCENE_DIR, output));
  }
}

async function writeFullFrames(from) {
  for (const pose of POSES) {
    const output = join(SCENE_DIR, `dragon-full-${pose}.webp`);
    await sharp(join(from, 'assets', `rear-keyed-${pose}.png`)).webp({ quality: 82, alphaQuality: 90 }).toFile(output);
    await report(output);
  }
}

function spineModule(spine) {
  const lines = [
    '/*',
    ' * Generated by scripts/prepare-scene.mjs from assets/rear-spine.json. Do not edit.',
    ' * Points of the dragon tail spine in the 800×706 frame of dragon-tail.webp.',
    ' */',
    'export const DRAGON_SPINE = {',
    `  w: ${spine.w},`,
    `  h: ${spine.h},`,
    `  half: ${spine.half},`,
  ];
  for (const key of SPINE_ARRAYS) {
    if (!Array.isArray(spine[key]) || spine[key].length !== 90) throw new Error(`rear-spine.json: "${key}" must have 90 numbers`);
    lines.push(`  ${key}: [${spine[key].join(', ')}],`);
  }
  lines.push('} as const;', '');
  return lines.join('\n');
}

async function writeSpine(from) {
  const spine = JSON.parse(await readFile(join(from, 'assets', 'rear-spine.json'), 'utf8'));
  await mkdir(join(SPINE_OUT, '..'), { recursive: true });
  await writeFile(SPINE_OUT, spineModule(spine));
  await report(SPINE_OUT);
}

async function encodeSong(from, ffmpeg) {
  const input = join(from, 'audio', 'RideTheWind.mp3');
  const sha = createHash('sha256').update(await readFile(input)).digest('hex');
  if (sha !== SONG_SHA256) throw new Error(`RideTheWind.mp3 sha256 is ${sha}, expected ${SONG_SHA256}`);
  await mkdir(join(AUDIO_OUT, '..'), { recursive: true });
  const args = ['-hide_banner', '-y', '-i', input, '-map', '0:a:0', '-c:a', 'libmp3lame', '-b:a', '112k', '-ar', '44100', '-ac', '2', '-id3v2_version', '3', AUDIO_OUT];
  execFileSync(ffmpeg, args, { stdio: ['ignore', 'ignore', 'inherit'] });
  await report(AUDIO_OUT);
}

async function main() {
  const { from, ffmpeg, skipAudio } = parseArgs(process.argv.slice(2));
  await mkdir(SCENE_DIR, { recursive: true });
  await writePaintings(from);
  await copyDragonFrames(from);
  await writeFullFrames(from);
  await writeSpine(from);
  if (skipAudio) console.log('public/audio/ride-the-wind.mp3  skipped (--skip-audio)');
  else await encodeSong(from, ffmpeg);
}

try {
  await main();
} catch (error) {
  console.error(error instanceof Error ? error.message : error);
  if (error instanceof UsageError) console.error(USAGE);
  process.exit(error instanceof UsageError ? 2 : 1);
}
